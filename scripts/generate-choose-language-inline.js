#!/usr/bin/env node
/**
 * Generates client/src/generated/choose-language-titles.ts from every locale
 * JSON file's `onboarding.chooseLanguageTitle` value.
 *
 * Why this exists: the AdaptiveLanguageSubheader on the language-selection
 * page needs all 21 "Choose your language" translations available on the
 * very first render so a visitor whose browser language is non-English never
 * sees a flash of English before the bundle-loaded native translation
 * arrives. Eagerly loading the full 21 locale bundles on the main page
 * would add ~300 KB gzipped to every visitor's entry bundle; inlining just
 * this one key across 21 locales is ~400 bytes gzipped.
 *
 * The generated file is committed to the repo so dev, prerender, and CI all
 * have a consistent view. Rerun this script whenever a locale JSON's
 * `onboarding.chooseLanguageTitle` changes. The check mode (--check) exits
 * non-zero if the generated file is stale — used by the pre-commit hook to
 * guarantee the two sources never drift.
 *
 * Run: node scripts/generate-choose-language-inline.js
 * Check (no write, just verify in-sync): node scripts/generate-choose-language-inline.js --check
 */

import { readFileSync, writeFileSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);
const ROOT = join(__dirname, '..');

// Keep this list synchronised with client/src/i18n.ts SUPPORTED_LOCALES.
// The validator below warns if the two drift. Order follows SUPPORTED_LOCALES
// so generated output is deterministic.
const LOCALES = [
  'en', 'zh-Hans', 'zh-Hant', 'hi', 'es', 'ar', 'fr',
  'bn', 'pt-BR', 'ru', 'ur', 'id', 'de',
  'ja', 'vi', 'tr', 'ko', 'tl', 'it', 'th', 'ms',
];

const OUTPUT_PATH = join(ROOT, 'src/generated/choose-language-titles.ts');
const KEY_PATH = ['onboarding', 'chooseLanguageTitle'];

function readTranslation(locale) {
  const filePath = join(ROOT, `src/locales/${locale}.json`);
  const json = JSON.parse(readFileSync(filePath, 'utf8'));
  let node = json;
  for (const segment of KEY_PATH) {
    if (node == null || typeof node !== 'object' || !(segment in node)) {
      throw new Error(
        `${locale}.json is missing ${KEY_PATH.join('.')}`,
      );
    }
    node = node[segment];
  }
  if (typeof node !== 'string') {
    throw new Error(
      `${locale}.json ${KEY_PATH.join('.')} is not a string (got ${typeof node})`,
    );
  }
  return node;
}

function escapeSingleQuotes(s) {
  return s.replace(/\\/g, '\\\\').replace(/'/g, "\\'");
}

function buildOutput() {
  const lines = [];
  lines.push('// GENERATED by scripts/generate-choose-language-inline.js — DO NOT EDIT BY HAND.');
  lines.push('// Source: client/src/locales/*.json (onboarding.chooseLanguageTitle).');
  lines.push('// Rerun the generator after any locale JSON update; the pre-commit hook verifies parity.');
  lines.push('');
  lines.push("import type { SupportedLocale } from '../i18n.ts';");
  lines.push('');
  lines.push('/**');
  lines.push(' * Inline map of every shipped locale’s "Choose your language"');
  lines.push(' * translation. Used by AdaptiveLanguageSubheader so the first render');
  lines.push(' * has the visitor’s detected locale available synchronously, with no');
  lines.push(' * flash of English while the lazy-loaded locale bundle fetches.');
  lines.push(' */');
  lines.push('export const CHOOSE_LANGUAGE_TITLES: Record<SupportedLocale, string> = {');
  for (const locale of LOCALES) {
    const value = readTranslation(locale);
    const key = /^[a-z]+$/i.test(locale) ? locale : `'${locale}'`;
    lines.push(`  ${key}: '${escapeSingleQuotes(value)}',`);
  }
  lines.push('};');
  lines.push('');
  return lines.join('\n');
}

function main() {
  const checkOnly = process.argv.includes('--check');
  const expected = buildOutput();

  let existing = null;
  try {
    existing = readFileSync(OUTPUT_PATH, 'utf8');
  } catch (err) {
    if (err.code !== 'ENOENT') throw err;
  }

  if (checkOnly) {
    if (existing !== expected) {
      console.error('FAIL: choose-language-titles.ts is out of sync with the locale JSONs.');
      console.error('Run: node scripts/generate-choose-language-inline.js');
      console.error('Then stage the regenerated file and retry the commit.');
      process.exit(1);
    }
    console.log('choose-language-titles.ts is in sync with the locale JSONs.');
    return;
  }

  writeFileSync(OUTPUT_PATH, expected, 'utf8');
  console.log(`Wrote ${OUTPUT_PATH} (${LOCALES.length} locales).`);
}

main();
